// Phone remote, player-written prompts, following the TV to a new room, streamer mode.
import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const base = 'http://localhost:8765/';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const errors = [];
const tv = await ctx.newPage(); tv.on('pageerror', e => errors.push('tv ' + e.message));
await tv.goto(base + 'tv.html?local=1'); await tv.waitForSelector('.code');
const code = (await tv.textContent('.code')).trim();
const me = await ctx.newPage(); me.on('pageerror', e => errors.push('me ' + e.message));
await me.setViewportSize({ width: 390, height: 800 });
await me.goto(base + 'play.html?local=1'); await me.fill('#code', code); await me.fill('#name', 'Tom'); await me.click('#join');
await me.waitForSelector("text=You're in");
const H = () => tv.evaluate(() => JSON.parse(localStorage.getItem('pg-host')));
const out = {};
await tv.click('[data-host=settings]'); await tv.click('[data-host=newcode]'); await tv.waitForTimeout(4500);
out.moved = (await H()).players.map(p => p.name).join(',') + ' in ' + (await H()).code + (code !== (await H()).code ? ' (new)' : ' (same!)');
await tv.click('[data-host=settings]'); await tv.click('[data-host=streamer]'); out.streamer = await tv.evaluate(() => document.body.classList.contains('streamer')); await tv.click('[data-host=streamer]'); await tv.click('[data-host=menu]');
for (let i = 0; i < 3; i++) await tv.click('[data-host=addbot]');
await tv.click('[data-game=funny]'); await me.waitForSelector('#pt');
await me.fill('#pt', 'The worst thing to say to a llama'); await me.click('#pf button'); await tv.waitForTimeout(1200);
out.custom = ((await H()).custom || []).map(c => c.text);
await me.click('[data-rm=start]'); await tv.waitForTimeout(1500);
out.started = (await H()).state?.game; out.customInGame = (await H()).state?.custom;
console.log(JSON.stringify(out)); console.log(await me.evaluate(() => document.querySelector('#app').innerText.slice(0,200)));
await me.waitForSelector('.hostbtn', { timeout: 8000 }); await me.click('#hsok', { timeout: 1500 }).catch(() => {}); await me.click('.hostbtn'); await me.click('[data-rm=pause]'); await tv.waitForTimeout(800);
out.paused = !!(await H()).paused;
console.log(JSON.stringify(out), 'errors', errors);
await b.close(); process.exit(errors.length ? 1 : 0);
