import { chromium } from '/opt/npm-tools/node_modules/playwright/index.mjs';
const base = 'http://localhost:8765/';
const b = await chromium.launch({ executablePath: '/usr/bin/google-chrome' });
const ctx = await b.newContext({ viewport: { width: 1280, height: 720 } });
const errors = [];
const tv = await ctx.newPage(); tv.on('pageerror', e => errors.push('tv ' + e.message));
await tv.goto(base + 'tv.html?local=1'); await tv.waitForSelector('.code');
const code = (await tv.textContent('.code')).trim();
const me = await ctx.newPage(); me.on('pageerror', e => errors.push('me ' + e.message));
await me.setViewportSize({ width: 390, height: 780 });
await me.goto(base + 'play.html?local=1'); await me.fill('#code', code); await me.fill('#name', 'Tom'); await me.click('form .btn');
await me.waitForSelector("text=You're in");
for (let i = 0; i < 5; i++) await tv.click('[data-host=addbot]');
await tv.screenshot({ path: 'test/l-lobby.png' });
await tv.click('[data-host=start]');
await tv.waitForTimeout(900); await tv.screenshot({ path: 'test/l-title.png' });
await me.click('[data-ready]');
await tv.waitForTimeout(9000);
await tv.screenshot({ path: 'test/l-night.png' });
await me.screenshot({ path: 'test/l-phone-night.png' });
const st = () => tv.evaluate(() => JSON.parse(localStorage.getItem('pg-host')).state);
for (let i = 0; i < 40; i++) { const s = await st(); if (s.phase === 'day') break; const o = await me.$('[data-pick]'); if (o && !(await me.$('.opt.on'))) await o.click(); await tv.waitForTimeout(1000); }
await tv.waitForTimeout(4200); await tv.screenshot({ path: 'test/l-day.png' }); await me.screenshot({ path: 'test/l-phone-day.png' });
console.log((await st()).phase, errors);
await b.close();
